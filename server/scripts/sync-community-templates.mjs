// Copies each template's template.json from ../templates/<slug>/ into src/templates/community-data.ts.
//
// Why a generated copy: the production image only contains server/, and a registry must publish the exact bytes of
// each template. Run this after a template changes, then commit the result:
//
//   cd server && node scripts/sync-community-templates.mjs
//
// test/community-templates.test.ts fails if the copy and the template.json files drift apart.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const slugs = ['badgers-stake', 'block-points', 'drip-mine', 'revenue-split', 'token-burner'];

let out = `// GENERATED by scripts/sync-community-templates.mjs from ../templates/<slug>/template.json. Do not edit by hand.\n`;

out += `// Each value is the template file's exact text.\n\n`;
out += `export const COMMUNITY_TEMPLATE_JSON: Record<string, string> = {\n`;

for (const slug of slugs) {
    const text = readFileSync(join(here, '..', '..', 'templates', slug, 'template.json'), 'utf8');

    out += `    ${JSON.stringify(slug)}: ${JSON.stringify(text)},\n`;
}

out += `};\n`;
writeFileSync(join(here, '..', 'src', 'templates', 'community-data.ts'), out);
console.log(`Wrote src/templates/community-data.ts (${slugs.length} templates).`);
